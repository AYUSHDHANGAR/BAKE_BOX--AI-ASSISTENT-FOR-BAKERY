"""
Database utility module for BAKEBOX backend.
Provides a simple connection pool using ibm_db and a context manager.
"""
import os
import ibm_db
import ibm_db_dbi
from contextlib import contextmanager
from typing import Generator, Dict, Any

# Build DSN from environment variables (loaded via config)
DB_HOST = os.getenv("DB_HOST", "127.0.0.1")
DB_PORT = os.getenv("DB_PORT", "50000")
DB_DATABASE = os.getenv("DB_DATABASE", "IBMDB201")
DB_USER = os.getenv("DB_USER", "dbayush")
DB_PASSWORD = os.getenv("DB_PASSWORD", "8844")

DSN = (
    f"DATABASE={DB_DATABASE};"
    f"HOSTNAME={DB_HOST};"
    f"PORT={DB_PORT};"
    f"PROTOCOL=TCPIP;"
    f"UID={DB_USER};"
    f"PWD={DB_PASSWORD};"
)

def get_connection() -> ibm_db_dbi.Connection:
    """Create and return a new DB2 connection.
    Caller must close the connection when done.
    """
    return ibm_db_dbi.connect(DSN, "", "")

@contextmanager
def get_db() -> Generator[ibm_db_dbi.Connection, None, None]:
    """FastAPI dependency that yields a DB connection and ensures cleanup."""
    conn = get_connection()
    try:
        yield conn
    finally:
        conn.close()

def query_one(conn: ibm_db_dbi.Connection, sql: str, params: tuple = ()) -> Dict[str, Any]:
    """Execute a SELECT that returns a single row as a dict."""
    cursor = conn.cursor()
    cursor.execute(sql, params)
    row = cursor.fetchone()
    if row is None:
        return {}
    columns = [desc[0] for desc in cursor.description]
    return dict(zip(columns, row))

def query_all(conn: ibm_db_dbi.Connection, sql: str, params: tuple = ()) -> list[Dict[str, Any]]:
    """Execute a SELECT that returns multiple rows as a list of dicts."""
    cursor = conn.cursor()
    cursor.execute(sql, params)
    rows = []
    for row in cursor.fetchall():
        columns = [desc[0] for desc in cursor.description]
        rows.append(dict(zip(columns, row)))
    return rows

def execute_dml(conn: ibm_db_dbi.Connection, sql: str, params: tuple = ()) -> bool:
    """Execute an INSERT/UPDATE/DELETE statement. Returns True on success."""
    cursor = conn.cursor()
    cursor.execute(sql, params)
    conn.commit()
    return True

def init_db():
    """Create minimal tables if they do not exist. Called on app startup.
    For production, use Alembic migrations.
    """
    conn = get_connection()
    try:
        # Users table (basic auth)
        conn.exec_immediate(
            """
            CREATE TABLE IF NOT EXISTS users (
                user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email VARCHAR(255) NOT NULL UNIQUE,
                password_hash VARCHAR(255) NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT TIMESTAMP
            )
            """
        )
        # Products table (minimal fields for demo)
        conn.exec_immediate(
            """
            CREATE TABLE IF NOT EXISTS products (
                sku_id VARCHAR(50) PRIMARY KEY,
                name VARCHAR(255),
                category VARCHAR(100),
                price_inr DECIMAL(10,2),
                image_url VARCHAR(500),
                rag_chunk CLOB
            )
            """
        )
        # Embeddings table – stores vector as binary BLOB and optional metadata
        conn.exec_immediate(
            """
            CREATE TABLE IF NOT EXISTS embeddings (
                embed_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                sku_id VARCHAR(50) NOT NULL,
                vector BLOB,
                metadata CLOB,
                CONSTRAINT fk_sku FOREIGN KEY (sku_id) REFERENCES products(sku_id) ON DELETE CASCADE
            )
            """
        )
    finally:
        conn.close()

